"""Generate data/agents/metro_24.json: a 24-utility metro for the scalability test.

Run once; the output JSON is committed, so scenarios stay plain data files.
Deterministic (fixed seed), so re-running produces the identical file.

    python3 scripts/gen_stress_agents.py
"""
import json
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "data" / "agents" / "metro_24.json"

# kind: (count, priority_rank, weight, min_kw range, desired/min ratio, reserve hours at min, crit)
KINDS = {
    "hospital":  (4, 1, 1.00, (220, 380), 1.5, 3.5, 8.0),
    "emergency": (5, 2, 0.90, (60, 140), 1.6, 2.0, 8.0),
    "water":     (6, 3, 0.75, (120, 260), 1.7, 4.0, 6.0),
    "telecom":   (6, 4, 0.60, (40, 90), 1.8, 4.0, 6.0),
    "shelter":   (3, 5, 0.50, (30, 70), 1.8, 2.5, 4.0),
}
NAMES = {
    "hospital": ["City General", "St. Martha's", "Children's Hospital", "Trauma Centre"],
    "emergency": ["Fire HQ", "Police Control", "Ambulance Depot", "Fire Station East", "Disaster Response Cell"],
    "water": ["Pump Stn North", "Pump Stn South", "Treatment Plant", "Booster East", "Booster West", "Reservoir Pumps"],
    "telecom": ["Core Exchange", "Tower Cluster A", "Tower Cluster B", "Tower Cluster C", "Data Centre", "Radio Relay"],
    "shelter": ["Relief Shelter 1", "Relief Shelter 2", "Stadium Shelter"],
}


def main():
    rng = random.Random(24)
    agents = []
    by_kind = {}
    for kind, (n, rank, w, (lo, hi), ratio, hours, crit) in KINDS.items():
        for i in range(n):
            mn = round(rng.uniform(lo, hi))
            aid = f"{kind}_{i + 1}"
            agents.append({
                "id": aid, "name": NAMES[kind][i], "kind": kind, "priority_rank": rank,
                "weight": w, "min_kw": mn, "desired_kw": round(mn * ratio),
                "reserve_capacity_kwh": round(mn * hours * rng.uniform(0.7, 1.3)),
                "reserve_initial_frac": round(rng.uniform(0.6, 0.95), 2),
                "max_discharge_kw": round(mn * rng.uniform(0.5, 0.9)),
                "recharge_kw": round(mn * 0.4),
                "damage_soft": 1.0, "damage_critical": crit,
                "escalation": 0.1 if rank <= 2 else 0.08, "escalation_cap_steps": 24,
            })
            by_kind.setdefault(kind, []).append(aid)
    deps = []
    # every emergency unit relies on a telecom node; every hospital on a water station
    for i, e in enumerate(by_kind["emergency"]):
        t = by_kind["telecom"][i % len(by_kind["telecom"])]
        deps.append({"source": t, "target": e, "impact": 0.35, "label": "dispatch comms"})
    for i, h in enumerate(by_kind["hospital"]):
        wtr = by_kind["water"][i % len(by_kind["water"])]
        deps.append({"source": wtr, "target": h, "impact": 0.25, "label": "water pressure"})
        t = by_kind["telecom"][(i + 1) % len(by_kind["telecom"])]
        deps.append({"source": t, "target": h, "impact": 0.10, "label": "coordination"})
    for i, s in enumerate(by_kind["shelter"]):
        wtr = by_kind["water"][(i + 2) % len(by_kind["water"])]
        deps.append({"source": wtr, "target": s, "impact": 0.30, "label": "drinking water"})
    OUT.write_text(json.dumps({
        "description": "Generated by scripts/gen_stress_agents.py (seed 24). 24 utilities for the scalability test.",
        "agents": agents, "dependencies": deps}, indent=1) + "\n")
    total_min = sum(a["min_kw"] for a in agents)
    total_des = sum(a["desired_kw"] for a in agents)
    print(f"wrote {OUT} : {len(agents)} agents, sum(min)={total_min} kW, sum(desired)={total_des} kW")


if __name__ == "__main__":
    main()
