"""Regenerate the results block of CITY.md from real runs. Never edit that block by hand.

Usage:  python3 scripts/generate_city_results.py   (also run by `python3 gridpact.py results`)
"""
import platform
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from gridpact import city as C  # noqa: E402

OUT = ROOT / "CITY.md"
START, END = "<!-- CITY-RESULTS:START -->", "<!-- CITY-RESULTS:END -->"
ORDER = ["gridpact", "priority", "proportional", "equal"]
NAME = {"gridpact": "GridPact", "priority": "Strict priority", "proportional": "Proportional", "equal": "Equal split"}
SEED = 41


def m(v):
    return f"{v / 1e6:.2f} M"


def pct(a, b):
    return f"{100 * (a - b) / b:+.1f}%"


def main():
    t0 = time.perf_counter()
    c = C.load_city("mumbai")
    md = [START, "",
          f"*Generated by `scripts/generate_city_results.py` (seed {SEED}, {c['forecast']['members']} forecast "
          f"versions per disaster, Python {platform.python_version()}). Harm is in household-hours without power, "
          f"equivalent.*", ""]
    md += ["### Recorded inputs (intensity 1.0×)", "",
           "| Disaster | " + " | ".join(f"{NAME[p]} harm" for p in ORDER)
           + " | GridPact vs best baseline | GridPact vs proportional | Lowest-harm forecast versions | Capacity violations |",
           "|---|" + "---:|" * (len(ORDER) + 4)]
    detail = []
    total_viol = total_runs = 0
    for d in sorted(c["disasters"], key=lambda d: d["order"]):
        r = C.run_city("mumbai", d["id"], 1.0, SEED)
        P, F = r["policies"], r["forecast"]
        best = min(P[p]["harm"] for p in ORDER if p != "gridpact")
        viol = sum(P[p]["violations"] for p in ORDER) + r["forecast_violations"]
        total_viol += viol
        total_runs += len(ORDER) * (r["forecast_members"] + 1)
        md.append(f"| {d['name']} | " + " | ".join(m(P[p]["harm"]) for p in ORDER)
                  + f" | {pct(P['gridpact']['harm'], best)} | {pct(P['gridpact']['harm'], P['proportional']['harm'])}"
                  + f" | {r['forecast_wins']}/{r['forecast_members']} | {viol} |")
        detail += [f"#### {d['name']}", "",
                   "| Policy | Harm, median (p10–p90) | Homes dark, household-h | Water reduced, resident-h | "
                   "Hospital beds on reduced power, bed-h | Mobile degraded, resident-h | Critical failures |",
                   "|---|---:|---:|---:|---:|---:|---:|"]
        for p in ORDER:
            f = F[p]
            detail.append(f"| {NAME[p]} | {m(f['harm']['p50'])} ({m(f['harm']['p10'])}–{m(f['harm']['p90'])}) | "
                          f"{m(f['homes_dark_hh_h']['p50'])} | {m(f['water_red_res_h']['p50'])} | "
                          f"{f['hospital_red_bed_h']['p50']:,.0f} | {m(f['telecom_red_res_h']['p50'])} | "
                          f"{f['failure_events']['p50']:.0f} |")
        detail.append("")
    md += ["", f"**{total_viol} capacity violations in {total_runs} runs.**", "",
           "### Forecast detail (median of the ensemble)", ""] + detail
    md += ["### Sensitivity to intensity (12 Oct 2020 replay)", "",
           "| Intensity | Supply left at 10:00 | GridPact vs best baseline | GridPact vs proportional | Homes dark (GridPact) |",
           "|---:|---:|---:|---:|---:|"]
    for k in (0.5, 0.75, 1.0, 1.25, 1.5):
        r = C.run_city("mumbai", "grid_2020", k, SEED, members=1)
        P = r["policies"]
        best = min(P[p]["harm"] for p in ORDER if p != "gridpact")
        sup = P["gridpact"]["series"]["supply_mw"][40]
        md.append(f"| {k:.2f}× | {sup:,.0f} MW | {pct(P['gridpact']['harm'], best)} | "
                  f"{pct(P['gridpact']['harm'], P['proportional']['harm'])} | {m(P['gridpact']['homes_dark_hh_h'])} |")
    md += ["", f"*Generated in {time.perf_counter() - t0:.1f} s.*", "", END]
    text = OUT.read_text()
    a, b = text.index(START), text.index(END) + len(END)
    OUT.write_text(text[:a] + "\n".join(md) + text[b:])
    print(f"wrote {OUT.name} results block")


if __name__ == "__main__":
    main()
