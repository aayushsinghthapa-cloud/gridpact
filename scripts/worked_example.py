"""Trace ONE real contested step, round by round, and write it into ALGORITHM.md.

    python3 scripts/worked_example.py

Nothing here is typed by hand: it runs the real simulator (Cyclone landfall,
seed 41), snapshots the private states just before the chosen step, runs the
step, and prints every number the protocol used. The output replaces the text
between the WORKED-EXAMPLE markers in ALGORITHM.md.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from gridpact import agent as A                      # noqa: E402
from gridpact.config import load_scenario            # noqa: E402
from gridpact.simulation import Simulation           # noqa: E402

SCENARIO, SEED, STEP = "cyclone_landfall", 41, 38    # 09:30, mid-storm, hold + phase-1 rounds
START, END = "<!-- WORKED-EXAMPLE:START -->", "<!-- WORKED-EXAMPLE:END -->"


def kw(w):
    return f"{w / 1000:.1f}"


def main():
    sc = load_scenario(SCENARIO)
    sim = Simulation(sc, SEED, "gridpact")
    for _ in range(STEP):
        sim.step()
    before = sim.state.agent_map()           # private states, BEFORE the step
    rec = sim.step()
    agents = sim.agents
    ids = [a.id for a in sc.agents]
    name = {a.id: a.name for a in sc.agents}
    dt = sc.dt_hours
    out = []
    p = out.append

    p(f"*Generated by `scripts/worked_example.py` from a real run: {sc.name}, seed {SEED}, "
      f"step {STEP} (clock {int(rec['hour']):02d}:{int(round(rec['hour'] % 1 * 60)):02d}, {rec['hour']:g} h into the scenario). "
      f"Re-run the script to regenerate; do not edit by hand.*")
    p("")
    p(f"**Step 1. Grid announces supply:** S = **{rec['supply_kw']:.3f} kW** "
      f"(= {rec['supply_w']:,} W, the integer the validator checks).")
    if rec["active_effects"]:
        p(f"Active events: {', '.join(rec['active_effects'])}.")
    p("")
    p("**Step 2. Each agent computes its request and bid from its own private state.**")
    p("")
    p("| Agent | Demand factor | Desired | Critical min | Reserve | Discharge available | Recharge want | "
      "Request max | Request min (hard floor) |")
    p("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for a in ids:
        ag, st, r = agents[a], before[a], rec["agents"][a]
        st = st.__class__(**{**st.__dict__, "demand_factor": r["desired_kw"] / ag.cfg.desired_kw})
        p(f"| {name[a]} | ×{st.demand_factor:.2f} | {ag.desired_kw(st):.1f} kW | {ag.min_kw(st):.1f} kW | "
          f"{st.reserve_kwh:.1f} kWh ({ag.reserve_frac(st):.1%}) | {ag.discharge_available_kw(st, dt):.1f} kW | "
          f"{ag.recharge_want_kw(st, dt):.1f} kW | {r['request_max_kw']:.3f} kW | {r['request_min_kw']:.3f} kW |")
    p("")
    p("Request max = desired + recharge want. Request min = max(0, critical min − discharge available), "
      "rounded **up** to whole watts.")
    p("")
    p("Urgency bid u = weight × (1 + e × streak) × (1 + γ × (1 − reserve fraction)) × (1 + β × credits), "
      f"with γ = {A.GAMMA_RESERVE}, β = {A.BETA_CREDITS}:")
    p("")
    p("| Agent | weight | streak (e) | escalation | reserve fraction | scarcity | credits | credit factor | **bid u** |")
    p("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for a in ids:
        ag, st = agents[a], before[a]
        c = ag.cfg
        streak = min(st.shortfall_streak, c.escalation_cap_steps)
        esc = 1 + c.escalation * streak
        rf = ag.reserve_frac(st)
        scar = 1 + A.GAMMA_RESERVE * (1 - rf)
        cf = 1 + A.BETA_CREDITS * st.credits
        p(f"| {name[a]} | {c.weight} | {st.shortfall_streak} ({c.escalation}) | {esc:.2f} | {rf:.4f} | {scar:.4f} | "
          f"{st.credits:.3f} | {cf:.4f} | **{rec['agents'][a]['bid']:.4f}** |")
    total_max = sum(rec["agents"][a]["request_max_kw"] for a in ids)
    p("")
    p(f"**Step 3. Contested?** Total requested = {total_max:.3f} kW > supply {rec['supply_kw']:.3f} kW, "
      f"so the excess to remove is **{total_max - rec['supply_kw']:.3f} kW**. Negotiation opens.")
    p("")
    p("**Step 4. Rounds.** Each agent's phase-1 floor: its hard floor if reserve ≥ 30%, otherwise its full "
      "critical min (it *holds firm*). In each round every agent that can still concede takes the share "
      "(1/u_i) / Σ(1/u_j) of the remaining excess, capped at 25% of its phase slack and at its floor. "
      "All agents decide from the same public snapshot.")
    p("")
    holds = [l for l in rec["log"] if l["kind"] == "hold"]
    for l in holds:
        p(f"- {l['text']}")
    if holds:
        p("")
    # replay the offers round by round from the log
    offers = {a: round(rec["agents"][a]["request_max_kw"] * 1000) for a in ids}
    rounds = sorted({l["round"] for l in rec["log"] if l["kind"] == "concede"})
    p("| Round | " + " | ".join(name[a] for a in ids) + " | Σ offers | Excess after |")
    p("|---:|" + "---:|" * (len(ids) + 2))
    p("| start | " + " | ".join(kw(offers[a]) for a in ids) + f" | {kw(sum(offers.values()))} | "
      f"{kw(sum(offers.values()) - rec['supply_w'])} |")
    for rd in rounds:
        moves = {l["agent"]: l["watts"] for l in rec["log"] if l["kind"] == "concede" and l["round"] == rd}
        for a, w in moves.items():
            offers[a] -= w
        cells = [f"{kw(offers[a])} (−{kw(moves[a])})" if a in moves else kw(offers[a]) for a in ids]
        p(f"| R{rd} | " + " | ".join(cells) + f" | {kw(sum(offers.values()))} | "
          f"{kw(max(0, sum(offers.values()) - rec['supply_w']))} |")
    p("")
    agree = [l for l in rec["log"] if l["kind"] in ("agree", "fallback")]
    for l in agree:
        p(f"Result: {l['text']}")
    p("")
    p("**Fairness ledger** (share = conceded ÷ desired; Δcredits = "
      f"{A.CREDIT_RATE:g} × (share − average share)):")
    p("")
    for l in rec["log"]:
        if l["kind"] == "credit":
            p(f"- {l['text']}")
    p("")
    p("**Step 5. Validator** (integer watts):")
    p("")
    for v in rec["validator"]:
        for c in v["checks"]:
            p(f"- {'✔' if c['ok'] else '✘'} {c['name']}: {c['detail']}")
    p("")
    p(f"Committed atomically: the engine swapped in the new state for step {STEP + 1}.")
    p("")
    p("**Step 6. Physics after the deal** (load first, then reserve covers the gap per the agent's discharge policy):")
    p("")
    p("| Agent | Allocated | Reserve discharge | Served | Status | Reserve after | Credits after | Damage this step |")
    p("|---|---:|---:|---:|---|---:|---:|---:|")
    for a in ids:
        r = rec["agents"][a]
        p(f"| {name[a]} | {r['alloc_kw']:.3f} kW | {r['discharge_kw']:.3f} kW | {r['served_kw']:.3f} kW | "
          f"{r['status']} | {r['reserve_frac']:.1%} | {r['credits']:.3f} | {r['damage']:.3f} |")
    p("")
    p(f"Step damage {rec['step_damage']:.3f}; cumulative {rec['total_damage']:.3f}.")

    doc = ROOT / "ALGORITHM.md"
    text = doc.read_text()
    i, j = text.index(START) + len(START), text.index(END)
    doc.write_text(text[:i] + "\n" + "\n".join(out) + "\n" + text[j:])
    print(f"wrote worked example (step {STEP}) into {doc}")


if __name__ == "__main__":
    main()
